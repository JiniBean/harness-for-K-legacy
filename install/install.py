"""Harness installer: links canonical files into tool-specific locations.

Usage:
  python install.py global --tools claude,cursor,codex [--home DIR] [--dry-run]
  python install.py project <root> --tools claude,cursor,codex [--dry-run]

global  = bootstrap: links core/ (harness_config, harness-guide, hook_io, gen_hook_configs) and
          install/set-up-harness into ~/.agents, records [harness] repo_dir, then per-tool links
          for what ~/.agents already holds (AGENTS.md import, skills). Rerun it after set-up-harness
          installs features globally.
project = per-tool links and Codex files for a project whose .agents/ set-up-harness filled.

Rules:
- Never overwrites anything that is not already the expected link/generated file.
  Such cases are reported as "conflict" and make the exit code non-zero.
- Links are symlinks. On Windows without symlink privilege, directories fall back
  to junctions; files are reported as errors (no hardlinks, no copies).
- --dry-run prints the same action lines and writes nothing.
"""

import argparse
import json
import os
import re
import subprocess
import sys
import tomllib
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
CORE = REPO / "core"
TOOLS = ("claude", "cursor", "codex")
# Global base (bootstrap): <~/.agents subpath> -> repo source. Features are added later by set-up-harness.
BOOTSTRAP_LINKS = (
    ("scripts/harness_config.py", CORE / "harness_config.py"),
    ("docs/harness-guide.md", CORE / "harness-guide.md"),
    ("hooks/hook_io.py", CORE / "hook_io.py"),
    ("hooks/gen_hook_configs.py", CORE / "gen_hook_configs.py"),
    ("skills/set-up-harness", REPO / "install" / "set-up-harness"),
)
CLAUDE_IMPORT = "@~/.agents/AGENTS.md"
MCP_BEGIN = "# >>> harness mcp (generated) >>>"
MCP_END = "# <<< harness mcp <<<"
GEN_HEADER = "# generated by harness install.py from {src}; edit the source, then rerun install"


class Runner:
    def __init__(self, dry_run):
        self.dry = dry_run
        self.counts = {}
        self.failed = False
        self.planned = set()  # links a dry run would create, so later steps can depend on them

    def report(self, action, path, target=None, note=None):
        self.counts[action] = self.counts.get(action, 0) + 1
        if action in ("conflict", "error"):
            self.failed = True
        line = f"{action:<8} {path}"
        if target is not None:
            line += f" -> {target}"
        if note:
            line += f"  ({note})"
        print(line)

    def summary(self):
        parts = ", ".join(f"{k}={v}" for k, v in sorted(self.counts.items()))
        print(f"\nsummary: {parts or 'nothing to do'}" + ("  [dry-run, nothing written]" if self.dry else ""))
        if self.failed:
            print("result: FAILED (resolve conflict/error lines above, then rerun)")
        return 1 if self.failed else 0

    # ---- filesystem primitives ----

    def mkdir(self, path):
        """Ensure a real directory. Returns False on conflict."""
        if is_link(path):
            self.report("conflict", path, note="expected a real folder, found a link")
            return False
        if path.is_dir():
            return True
        if path.exists():
            self.report("conflict", path, note="expected a folder, found a file")
            return False
        self.report("create", path)
        if not self.dry:
            path.mkdir(parents=True)
        return True

    def link(self, link, target, rel=False):
        """Create link -> target (absolute, or relative to link's folder if rel)."""
        target = Path(os.path.abspath(target))
        if not target.exists() and os.path.normcase(target) not in self.planned:
            self.report("skip", link, target, "source missing")
            return
        if is_link(link):
            if same_path(link_target(link), target):
                self.report("ok", link, target)
            else:
                self.report("conflict", link, target, f"link points elsewhere: {link_target(link)}")
            return
        if link.exists():
            self.report("conflict", link, target, "exists and is not a link")
            return
        if not self.dry and not self.mkdir_quiet(link.parent):
            return
        is_dir = target.is_dir()
        if self.dry:
            self.planned.add(os.path.normcase(link))
            self.report("link", link, target)
            return
        src = os.path.relpath(target, link.parent) if rel else str(target)
        try:
            os.symlink(src, link, target_is_directory=is_dir)
            self.report("link", link, target)
            return
        except OSError as e:
            if os.name != "nt" or getattr(e, "winerror", None) != 1314:
                self.report("error", link, target, str(e))
                return
        # Windows without symlink privilege (developer mode off)
        if not is_dir:
            self.report("error", link, target, "symlink needs Windows developer mode; file links have no fallback")
            return
        r = subprocess.run(["cmd", "/c", "mklink", "/J", str(link), str(target)],
                           capture_output=True, text=True)
        if r.returncode == 0:
            self.report("link", link, target, "junction")
        else:
            self.report("error", link, target, f"mklink /J failed: {(r.stdout + r.stderr).strip()}")

    def mkdir_quiet(self, path):
        if path.is_dir() and not is_link(path):
            return True
        return self.mkdir(path)

    def write_text(self, path, text, action):
        self.report(action, path)
        if not self.dry:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text, encoding="utf-8", newline="\n")


def is_link(p):
    p = Path(p)
    return p.is_symlink() or (hasattr(os.path, "isjunction") and os.path.isjunction(p))


def link_target(p):
    raw = os.readlink(p)
    if raw.startswith("\\\\?\\"):
        raw = raw[4:]
    t = Path(raw)
    if not t.is_absolute():
        t = Path(p).parent / t
    return Path(os.path.normpath(t))


def same_path(a, b):
    return os.path.normcase(os.path.normpath(a)) == os.path.normcase(os.path.normpath(b))


def posix(p):
    return str(p).replace("\\", "/")


# ---- global mode ----

def install_global(r, home, tools):
    """Bootstrap ~/.agents (loader, guide, hook_io, generator, set-up-harness), then per-tool
    links for whatever ~/.agents already holds. Rerun after set-up-harness installs global features."""
    agents = home / ".agents"
    if not r.mkdir(agents):
        return
    for sub, src in BOOTSTRAP_LINKS:
        dest = agents / sub
        if r.mkdir(dest.parent):
            r.link(dest, src)
    ensure_harness_toml(r, agents / "harness.toml")

    has_rules = (agents / "AGENTS.md").exists()  # agent-rules feature installed globally
    if "claude" in tools:
        if has_rules:
            ensure_line(r, home / ".claude" / "CLAUDE.md", CLAUDE_IMPORT)
        skills_dir = home / ".claude" / "skills"
        if r.mkdir(skills_dir):
            names = {p.name for p in (agents / "skills").iterdir()} if (agents / "skills").is_dir() else set()
            names |= {Path(sub).name for sub, _ in BOOTSTRAP_LINKS if sub.startswith("skills/")}
            for name in sorted(names - {"__pycache__"}):
                r.link(skills_dir / name, agents / "skills" / name)
    if "cursor" in tools and has_rules:
        print("note     cursor: paste ~/.agents/AGENTS.md into Settings > Rules > User Rules (Cursor does not read global instruction files)")
    if "codex" in tools and has_rules:
        r.link(home / ".codex" / "AGENTS.md", agents / "AGENTS.md")
    print("note     global hooks: set-up-harness fills ~/.agents/hooks/hooks.toml, then runs "
          "python ~/.agents/hooks/gen_hook_configs.py --scope global")


def ensure_harness_toml(r, path):
    value = posix(REPO)
    quoted = json.dumps(value, ensure_ascii=False)
    if not path.exists():
        example = (CORE / "harness.example.toml").read_text(encoding="utf-8")
        text, n = re.subn(r'(?m)^(\s*repo_dir\s*=\s*)("[^"]*"|\'[^\']*\')', lambda m: m.group(1) + quoted, example, count=1)
        if n == 0:
            text = f"[harness]\nrepo_dir = {quoted}\n\n" + example
        r.write_text(path, text, "create")
        return
    text = path.read_text(encoding="utf-8")
    try:
        current = tomllib.loads(text).get("harness", {}).get("repo_dir")
    except tomllib.TOMLDecodeError as e:
        r.report("conflict", path, note=f"not valid TOML, fix it first: {e}")
        return
    if current == value:
        r.report("ok", path, note="harness.repo_dir")
        return
    lines = text.splitlines(keepends=True)
    start = next((i for i, l in enumerate(lines) if re.match(r"\s*\[harness\]\s*(#.*)?$", l)), None)
    if start is None:
        sep = "" if text.endswith("\n") or not text else "\n"
        new = text + sep + f"\n[harness]\nrepo_dir = {quoted}\n"
    else:
        end = next((i for i in range(start + 1, len(lines)) if re.match(r"\s*\[", lines[i])), len(lines))
        key = next((i for i in range(start + 1, end) if re.match(r"\s*repo_dir\s*=", lines[i])), None)
        if key is None:
            lines.insert(start + 1, f"repo_dir = {quoted}\n")
        else:
            m = re.match(r'(\s*repo_dir\s*=\s*)("[^"]*"|\'[^\']*\')?(.*)$', lines[key].rstrip("\r\n"))
            rest = m.group(3) if m.group(2) is not None else ""
            eol = "\r\n" if lines[key].endswith("\r\n") else "\n"
            lines[key] = m.group(1) + quoted + rest + eol
        new = "".join(lines)
    tomllib.loads(new)  # never write invalid TOML
    r.report("edit", path, note="harness.repo_dir")
    if not r.dry:
        path.write_text(new, encoding="utf-8", newline="")


def ensure_line(r, path, line):
    if path.exists():
        text = path.read_text(encoding="utf-8")
        if any(l.strip() == line for l in text.splitlines()):
            r.report("ok", path, note=line)
            return
        sep = "" if text.endswith("\n") or not text else "\n"
        r.report("edit", path, note=f"append {line}")
        if not r.dry:
            path.write_text(text + sep + line + "\n", encoding="utf-8", newline="")
        return
    r.write_text(path, line + "\n", "create")


# ---- project mode ----

def install_project(r, root, tools):
    agents = root / ".agents"
    if not agents.is_dir():
        r.report("conflict", agents, note="project has no .agents folder (run set-up-harness first)")
        return
    if "claude" in tools:
        r.link(root / ".claude" / "skills", agents / "skills", rel=True)
        r.link(root / ".claude" / "agents", agents / "agents", rel=True)
        r.link(root / ".mcp.json", agents / "mcp.json", rel=True)
    if "cursor" in tools:
        r.link(root / ".cursor" / "agents", agents / "agents", rel=True)
        r.link(root / ".cursor" / "mcp.json", agents / "mcp.json", rel=True)
    if "codex" in tools:
        gen_codex_agents(r, root)
        gen_codex_mcp(r, root)


def parse_frontmatter(text):
    """Minimal YAML frontmatter reader: scalar keys and >- / | block scalars."""
    lines = text.splitlines()
    if not lines or lines[0].strip() != "---":
        return {}, text
    end = next((i for i in range(1, len(lines)) if lines[i].strip() == "---"), None)
    if end is None:
        return {}, text
    meta, i = {}, 1
    while i < end:
        m = re.match(r"([A-Za-z0-9_-]+):\s*(.*)$", lines[i])
        i += 1
        if not m:
            continue
        key, val = m.group(1), m.group(2).strip()
        if val[:1] in (">", "|"):
            block = []
            while i < end and (lines[i].startswith((" ", "\t")) or not lines[i].strip()):
                block.append(lines[i].strip())
                i += 1
            val = (" " if val[0] == ">" else "\n").join(b for b in block if b)
        elif len(val) >= 2 and val[0] == val[-1] and val[0] in "\"'":
            val = val[1:-1]
        meta[key] = val
    return meta, "\n".join(lines[end + 1:]).strip("\n") + "\n"


def toml_str(s):
    return json.dumps(s, ensure_ascii=False)  # JSON basic strings are valid TOML basic strings


def toml_key(k):
    return k if re.fullmatch(r"[A-Za-z0-9_-]+", k) else toml_str(k)


def toml_multiline(s):
    if "'''" not in s and not re.search(r"[\x00-\x08\x0b-\x1f\x7f]", s.replace("\r\n", "\n")):
        return "'''\n" + s + "'''"
    esc = s.replace("\\", "\\\\").replace('"', '\\"')
    esc = re.sub(r"[\x00-\x08\x0b-\x1f\x7f]", lambda m: "\\u%04x" % ord(m.group()), esc.replace("\r\n", "\n"))
    return '"""\n' + esc + '"""'


def gen_file(r, path, text, header):
    if path.exists():
        old = path.read_text(encoding="utf-8")
        if old == text:
            r.report("ok", path)
            return
        if not old.startswith(header):
            r.report("conflict", path, note="exists and was not generated by this script")
            return
    r.write_text(path, text, "gen")


def gen_codex_agents(r, root):
    src_dir = root / ".agents" / "agents"
    files = sorted(src_dir.glob("*.md")) if src_dir.is_dir() else []
    if not files:
        r.report("skip", root / ".codex" / "agents", src_dir, "source missing")
        return
    for md in files:
        meta, body = parse_frontmatter(md.read_text(encoding="utf-8"))
        name = meta.get("name") or md.stem
        header = GEN_HEADER.format(src=f".agents/agents/{md.name}")
        text = (f"{header}\n"
                f"name = {toml_str(name)}\n"
                f"description = {toml_str(meta.get('description', ''))}\n"
                f"developer_instructions = {toml_multiline(body)}\n")
        tomllib.loads(text)
        gen_file(r, root / ".codex" / "agents" / f"{name}.toml", text, header)


def gen_codex_mcp(r, root):
    src = root / ".agents" / "mcp.json"
    cfg = root / ".codex" / "config.toml"
    if not src.exists():
        r.report("skip", cfg, src, "source missing")
        return
    servers = json.loads(src.read_text(encoding="utf-8")).get("mcpServers", {})
    out = [MCP_BEGIN, "# source: .agents/mcp.json; edit it, then rerun install"]
    for name, s in servers.items():
        out.append(f"\n[mcp_servers.{toml_key(name)}]")
        if "command" in s:
            out.append(f"command = {toml_str(s['command'])}")
            if s.get("args"):
                out.append("args = [" + ", ".join(toml_str(a) for a in s["args"]) + "]")
        elif "url" in s:
            out.append(f"url = {toml_str(s['url'])}")
            if s.get("headers"):
                print(f"note     codex mcp '{name}': headers not converted (Codex uses bearer_token_env_var / env_vars)")
        else:
            r.report("skip", cfg, src, f"server '{name}' has neither command nor url")
            out.pop()
            continue
        if s.get("env"):
            out.append("env = { " + ", ".join(f"{toml_key(k)} = {toml_str(v)}" for k, v in s["env"].items()) + " }")
    out.append(MCP_END)
    block = "\n".join(out) + "\n"

    old = cfg.read_text(encoding="utf-8") if cfg.exists() else ""
    b, e = old.find(MCP_BEGIN), old.find(MCP_END)
    if b != -1 and e > b:
        new = old[:b] + block + old[e + len(MCP_END):].lstrip("\r\n")
    elif b == -1 and e == -1:
        new = old + ("\n" if old and not old.endswith("\n") else "") + ("\n" if old.strip() else "") + block
    else:
        r.report("conflict", cfg, note="broken managed block markers")
        return
    try:
        tomllib.loads(new)
    except tomllib.TOMLDecodeError as ex:
        r.report("conflict", cfg, note=f"result would not be valid TOML: {ex}")
        return
    if new == old:
        r.report("ok", cfg, note="mcp block")
    else:
        r.write_text(cfg, new, "gen")


def main(argv):
    if not argv:
        print(__doc__.strip())
        return 2
    ap = argparse.ArgumentParser(prog="install.py", description="Harness installer")
    sub = ap.add_subparsers(dest="mode", required=True)
    g = sub.add_parser("global", help="bootstrap ~/.agents and per-tool global files")
    g.add_argument("--home", type=Path, default=Path.home())
    p = sub.add_parser("project", help="link/generate per-tool files in a project")
    p.add_argument("root", type=Path)
    for sp in (g, p):
        sp.add_argument("--tools", required=True, help="comma list of: " + ",".join(TOOLS))
        sp.add_argument("--dry-run", action="store_true")
    a = ap.parse_args(argv)
    tools = {t.strip() for t in a.tools.split(",") if t.strip()}
    bad = tools - set(TOOLS)
    if bad or not tools:
        ap.error(f"unknown tools: {','.join(sorted(bad)) or '(none)'}; choose from {','.join(TOOLS)}")
    r = Runner(a.dry_run)
    if a.mode == "global":
        install_global(r, Path(os.path.abspath(a.home)), tools)
    else:
        root = Path(os.path.abspath(a.root))
        if not root.is_dir():
            ap.error(f"project root not found: {root}")
        install_project(r, root, tools)
    return r.summary()


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
